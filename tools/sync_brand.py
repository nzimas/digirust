"""Generate native drawing paths from the project's flat SVG logo assets.
Run after changing the SVGs; the native build uses the checked-in Swift output.
Supports the straight-line path commands used by this project's lettering.
"""
from pathlib import Path
import re,xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
def color(value):
 channels=[int(value[i:i+2],16)/255 for i in (1,3,5)]
 return 'CGColor(red: %.6f, green: %.6f, blue: %.6f, alpha: 1)'%tuple(channels)
def commands(d,tx,ty):
 tokens=re.findall(r'[MLHVZmlhvz]|[-+]?(?:\d*\.\d+|\d+)',d);out=[];i=0;x=y=sx=sy=0;cmd=None
 while i<len(tokens):
  if tokens[i].isalpha():cmd=tokens[i];i+=1
  upper=cmd.upper();relative=cmd.islower()
  if upper=='Z':out.append('p.closeSubpath()');x,y=sx,sy;cmd=None;continue
  if upper in ['M','L']:
   a,b=float(tokens[i]),float(tokens[i+1]);i+=2;x,y=(x+a,y+b) if relative else (a,b)
   out.append(f'p.{"move" if upper=="M" else "addLine"}(to: CGPoint(x: {x+tx:g}, y: {y+ty:g}))')
   if upper=='M':sx,sy=x,y;cmd='l' if relative else 'L'
  elif upper=='H':a=float(tokens[i]);i+=1;x=x+a if relative else a;out.append(f'p.addLine(to: CGPoint(x: {x+tx:g}, y: {y+ty:g}))')
  elif upper=='V':a=float(tokens[i]);i+=1;y=y+a if relative else a;out.append(f'p.addLine(to: CGPoint(x: {x+tx:g}, y: {y+ty:g}))')
  else:raise ValueError('Unsupported path command: '+cmd)
 return out
code=['// Generated by tools/sync_brand.py from the flat SVG assets.','import CoreGraphics','']
for asset,name in [('digirust-mark.svg','Emblem'),('digirust-logo.svg','Wordmark')]:
 root=ET.parse(ROOT/'web/assets'/asset).getroot();records=[]
 def walk(el,attrs,offset=(0,0)):
  local=el.attrib.get('transform','');tx,ty=offset
  if local:
   match=re.fullmatch(r'translate\(([-\d.]+)\s+([-\d.]+)\)',local);assert match,local;tx+=float(match[1]);ty+=float(match[2])
  attrs={**attrs,**el.attrib}
  if el.tag.endswith('path'):records.append((attrs,tx,ty))
  for child in el:walk(child,attrs,(tx,ty))
 walk(root,{})
 _,_,w,h=map(float,root.attrib['viewBox'].split())
 code += [f'func drawDigiRust{name}(_ context: CGContext, in bounds: CGRect) {{','    context.saveGState(); defer { context.restoreGState() }','    context.translateBy(x: bounds.minX, y: bounds.maxY)',f'    context.scaleBy(x: bounds.width / {w:g}, y: -bounds.height / {h:g})','    context.setLineJoin(.miter)','    context.setLineCap(.square)']
 for a,tx,ty in records:
  code+=['    do {','        let p = CGMutablePath()']+['        '+v for v in commands(a['d'],tx,ty)]+['        context.addPath(p)']
  fill=a.get('fill','none');stroke=a.get('stroke','none');even=a.get('fill-rule')=='evenodd'
  if fill!='none':code+=['        context.setFillColor('+color(fill)+')']
  if stroke!='none':code+=['        context.setStrokeColor('+color(stroke)+')','        context.setLineWidth('+a.get('stroke-width','1')+')']
  if fill!='none' and stroke!='none':op='drawPath(using: .eoFillStroke)' if even else 'drawPath(using: .fillStroke)'
  elif fill!='none':op='drawPath(using: .eoFill)' if even else 'fillPath()'
  else:op='strokePath()'
  code+=['        context.'+op,'    }']
 code+=['}','']
(ROOT/'Sources/Brand.swift').write_text('\n'.join(code))
print('Native emblem and custom lettering synchronized.')
